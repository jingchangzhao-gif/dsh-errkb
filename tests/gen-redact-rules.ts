// Generate the three redaction artifacts from the single rules document.
//
// Run it from the repository root:
//
//   pnpm exec tsdown tests/gen-redact-rules.ts \
//     --out-dir node_modules/.cache/errkb-gen --format esm --no-dts --no-config \
//     --external prettier
//   node node_modules/.cache/errkb-gen/gen-redact-rules.mjs          # write
//   node node_modules/.cache/errkb-gen/gen-redact-rules.mjs --check  # compare
//
// `--no-config` is required: the project `tsdown.config.ts` lists its peers in
// `deps.neverBundle`, and `--external` cannot be combined with that option. The
// bundle lives in `node_modules`, which is ignored by git, prettier and the
// privacy guard.
//
// The rules come from `spec/redact.cue` via `cue export`, so the Go engine, the
// TypeScript engine and the CI privacy guard can only disagree when generation
// is skipped. The output is deterministic: the same document always produces
// byte-identical files, which is what `--check` proves.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { format as prettierFormat } from "prettier";

const REPO_ROOT = process.cwd();
if (!existsSync(join(REPO_ROOT, "spec", "redact.cue")))
  throw new Error(`run from the repository root (cwd is ${REPO_ROOT})`);
const WORKFLOW = join(REPO_ROOT, ".github", "workflows", "privacy-guard.yml");
const GO_FILE = join(REPO_ROOT, "internal", "redact", "rules_gen.go");
const TS_FILE = join(REPO_ROOT, "src", "redact-patterns.ts");

const HEADER =
  "Code generated by tests/gen-redact-rules.ts from spec/redact.cue. DO NOT EDIT.";

interface Encoding {
  source: string;
  flags: string;
  mixed_case_digit?: boolean;
}

interface Rule {
  name: string;
  purpose: string;
  replacement: string;
  guard?: string;
  js: Encoding;
  go: Encoding;
  example: string[];
}

interface PathRule {
  name: string;
  purpose: string;
  pattern: string;
  replacement: string;
  example: string[];
}

interface HomePrefix {
  name: string;
  purpose: string;
  replacement: string;
  js: Encoding;
  go: PathRule[];
}

interface RulesDocument {
  schema_version: string;
  placeholders: Record<string, string>;
  rules: Rule[];
  home_prefix: HomePrefix[];
  path_guards: string[];
}

// Windows string quoting, byte for byte what `strconv.Quote` writes for the
// printable ASCII this document contains. The generated file stays readable and
// `gofmt` has nothing to reformat.
function goString(value: string): string {
  let out = '"';
  for (const character of value) {
    const code = character.codePointAt(0) as number;
    if (character === '"') out += '\\"';
    else if (character === "\\") out += "\\\\";
    else if (character === "\n") out += "\\n";
    else if (character === "\t") out += "\\t";
    else if (character === "\r") out += "\\r";
    else if (code < 0x20 || code === 0x7f)
      out += `\\x${code.toString(16).padStart(2, "0")}`;
    else out += character;
  }
  return out + '"';
}

// The privacy guard rejects credential-shaped literals in committed files, and
// the generated Go file is committed. An example therefore reaches the file as
// adjacent string literals that only become a fixture at run time.
function goExample(segments: string[]): string {
  return segments.map(goString).join(" + ");
}

function loadDocument(): RulesDocument {
  const raw = execFileSync(
    "cue",
    ["export", "./spec", "-e", "redact", "--out", "json"],
    { cwd: REPO_ROOT, encoding: "utf8" },
  );
  return JSON.parse(raw) as RulesDocument;
}

function validate(document: RulesDocument): void {
  if (document.schema_version !== "v1")
    throw new Error(`unexpected schema_version ${document.schema_version}`);
  const placeholders = Object.keys(document.placeholders).sort();
  if (placeholders.join(",") !== "base64,email,hex,request_id,secret")
    throw new Error(`unexpected placeholders: ${placeholders.join(",")}`);
  if (document.rules.length === 0) throw new Error("no text rules");
  const names = new Set<string>();
  const guards: string[] = [];
  for (const rule of document.rules) {
    if (rule.name === "" || names.has(rule.name))
      throw new Error(`duplicate or empty rule name: ${rule.name}`);
    names.add(rule.name);
    if (!rule.js.flags.includes("g"))
      throw new Error(`${rule.name}: js flags must be global`);
    if (rule.js.source === "" || rule.go.source === "")
      throw new Error(`${rule.name}: empty pattern`);
    if (rule.example.length === 0) throw new Error(`${rule.name}: no example`);
    if (rule.guard !== undefined) guards.push(rule.guard);
  }
  for (const home of document.home_prefix) {
    if (home.go.length === 0) throw new Error(`${home.name}: no Go encoding`);
    for (const variant of home.go)
      if (variant.example.length === 0)
        throw new Error(`${variant.name}: no example`);
  }
  for (const guard of [...guards, ...document.path_guards])
    if (guard.includes("'"))
      throw new Error(`guard alternative cannot be single-quoted: ${guard}`);
  const alternatives = [...guards, ...document.path_guards];
  if (new Set(alternatives).size !== alternatives.length)
    throw new Error("duplicate guard alternative");
}

function sourceDigest(document: RulesDocument): string {
  return createHash("sha256").update(JSON.stringify(document)).digest("hex");
}

// Go's regexp package has no per-call flags argument: JavaScript's `i` flag has
// to become the RE2 inline flag at the start of the source.
function goSource(source: string, flags: string): string {
  return flags.includes("i") ? `(?i)${source}` : source;
}

function emitGo(document: RulesDocument, digest: string): string {
  const text: string[] = [];
  text.push(
    `// ${HEADER}`,
    "",
    "// Package redact replaces credential and personal-data text before any",
    "// storage boundary: database, log or offline spool (§6). The rules below are",
    "// generated from spec/redact.cue; edit that document, not this file.",
    "package redact",
    "",
    'import "regexp"',
    "",
    "// SourceDigest is the SHA-256 of the rules document this file was generated",
    "// from. All three artifacts carry the same value; a mismatch means someone",
    "// edited a generated file by hand.",
    `const SourceDigest = ${goString(digest)}`,
    "",
    "// Rule is one text rule. Rules are applied in list order.",
    "type Rule struct {",
    "\tName string",
    "\tGuard string",
    "\tPattern *regexp.Regexp",
    "\tReplacement string",
    "\tMixedCaseDigit bool",
    "\tExample string",
    "}",
    "",
    "// rules are the credential and personal-data families, in application order.",
    "var rules = []Rule{",
  );
  for (const rule of document.rules) {
    text.push("\t{");
    text.push(`\t\tName: ${goString(rule.name)},`);
    text.push(`\t\tGuard: ${goString(rule.guard ?? "")},`);
    text.push(
      `\t\tPattern: regexp.MustCompile(${goString(goSource(rule.go.source, rule.js.flags))}),`,
    );
    text.push(`\t\tReplacement: ${goString(rule.replacement)},`);
    text.push(
      `\t\tMixedCaseDigit: ${rule.go.mixed_case_digit ? "true" : "false"},`,
    );
    text.push(`\t\tExample: ${goExample(rule.example)},`);
    text.push("\t},");
  }
  text.push(
    "}",
    "",
    "// PathRule is one home-directory rule applied in private mode.",
    "type PathRule struct {",
    "\tName string",
    "\tPattern *regexp.Regexp",
    "\tReplacement string",
    "\tExample string",
    "}",
    "",
    "// homePrefixRules keep the user name out of a path that is otherwise stored",
    "// whole. The replacement of the capture form restores the character before",
    "// the path, which the RE2 dialect cannot look behind.",
    "var homePrefixRules = []PathRule{",
  );
  for (const home of document.home_prefix)
    for (const variant of home.go) {
      text.push("\t{");
      text.push(`\t\tName: ${goString(variant.name)},`);
      text.push(
        `\t\tPattern: regexp.MustCompile(${goString(goSource(variant.pattern, home.js.flags))}),`,
      );
      text.push(`\t\tReplacement: ${goString(variant.replacement)},`);
      text.push(`\t\tExample: ${goExample(variant.example)},`);
      text.push("\t},");
    }
  text.push(
    "}",
    "",
    "// pathGuards are the privacy-guard alternatives that the path logic covers",
    "// rather than a text rule; the CI pattern is generated from the same list.",
    "var pathGuards = []string{",
  );
  for (const guard of document.path_guards) text.push(`\t${goString(guard)},`);
  text.push("}", "");
  return text.join("\n");
}

function emitTypeScript(document: RulesDocument, digest: string): string {
  const text: string[] = [];
  text.push(
    `// ${HEADER}`,
    "",
    "/** SHA-256 of the rules document all three artifacts were generated from. */",
    `export const REDACT_SOURCE_DIGEST = ${JSON.stringify(digest)};`,
    "",
    "/** Placeholders written in place of redacted text. */",
    "export const REDACTED = {",
    `  secret: ${JSON.stringify(document.placeholders.secret)},`,
    `  email: ${JSON.stringify(document.placeholders.email)},`,
    `  requestId: ${JSON.stringify(document.placeholders.request_id)},`,
    `  hex: ${JSON.stringify(document.placeholders.hex)},`,
    `  base64: ${JSON.stringify(document.placeholders.base64)},`,
    "} as const;",
    "",
    "/** A family of credential or personal-data text, and what replaces it. */",
    "export interface RedactPattern {",
    "  /** Stable family name, used in tests and in documentation. */",
    "  readonly name: string;",
    "  /** Global regular expression. */",
    "  readonly pattern: RegExp;",
    "  /** Replacement string; `$1`-style references keep a matched key name. */",
    "  readonly replacement: string;",
    "  /** The alternative in privacy-guard.yml this family covers, if any. */",
    "  readonly guard?: string;",
    "}",
    "",
    "/** Credential and personal-data families, in the order they are applied. */",
    "export const REDACT_PATTERNS: readonly RedactPattern[] = [",
  );
  for (const rule of document.rules) {
    const fields = [
      `name: ${JSON.stringify(rule.name)}`,
      `pattern: new RegExp(${JSON.stringify(rule.js.source)}, ${JSON.stringify(rule.js.flags)})`,
      `replacement: ${JSON.stringify(rule.replacement)}`,
    ];
    if (rule.guard !== undefined)
      fields.push(`guard: ${JSON.stringify(rule.guard)}`);
    text.push("  {", ...fields.map((field) => `    ${field},`), "  },");
  }
  text.push(
    "];",
    "",
    "/** Per-user home directories, replaced by ~ in private mode. */",
    "export const HOME_PREFIX: RegExp = new RegExp(",
    `  ${JSON.stringify(document.home_prefix[0]?.js.source ?? "")},`,
    `  ${JSON.stringify(document.home_prefix[0]?.js.flags ?? "g")},`,
    ");",
    "",
    "/** Privacy-guard alternatives covered by the path logic (public mode). */",
    "export const PATH_GUARDS: readonly string[] = [",
  );
  for (const guard of document.path_guards)
    text.push(`  ${JSON.stringify(guard)},`);
  text.push("];", "");
  return text.join("\n");
}

function emitWorkflow(document: RulesDocument, digest: string): string {
  const alternatives = [
    ...document.rules.flatMap((rule) =>
      rule.guard === undefined ? [] : [rule.guard],
    ),
    ...document.path_guards,
  ];
  const indent = "          ";
  const block = [
    "# BEGIN GENERATED REDACTION RULES - edit spec/redact.cue, then run",
    "# tests/gen-redact-rules.ts. Do not edit this block by hand.",
    `# redact-source-digest: ${digest}`,
    `PATTERN='${alternatives.join("|")}'`,
    "# END GENERATED REDACTION RULES",
  ]
    .map((line) => `${indent}${line}`)
    .join("\n");
  const current = readFileSync(WORKFLOW, "utf8");
  const markers =
    /^ {10}# BEGIN GENERATED REDACTION RULES[^\n]*\n[\s\S]*?^ {10}# END GENERATED REDACTION RULES$/m;
  if (!markers.test(current))
    throw new Error(
      `${WORKFLOW}: add the BEGIN/END GENERATED REDACTION RULES markers first`,
    );
  return current.replace(markers, block);
}

function gofmt(source: string): string {
  return execFileSync("gofmt", [], { input: source, encoding: "utf8" });
}

async function main(): Promise<void> {
  const document = loadDocument();
  validate(document);
  const digest = sourceDigest(document);
  const outputs = [
    {
      path: TS_FILE,
      content: await prettierFormat(emitTypeScript(document, digest), {
        parser: "typescript",
      }),
    },
    { path: GO_FILE, content: gofmt(emitGo(document, digest)) },
    { path: WORKFLOW, content: emitWorkflow(document, digest) },
  ];
  const check = process.argv.includes("--check");
  if (check) {
    const stale = outputs.filter(
      (output) => readFileSync(output.path, "utf8") !== output.content,
    );
    if (stale.length > 0) {
      console.error(
        `redaction artifacts differ from spec/redact.cue:\n${stale
          .map((output) => `  ${output.path}`)
          .join("\n")}\nrun the generator without --check`,
      );
      process.exitCode = 1;
      return;
    }
    console.log(`redaction artifacts up to date (${outputs.length} files)`);
    return;
  }
  for (const output of outputs) writeFileSync(output.path, output.content);
  console.log(`redaction artifacts written (${outputs.length} files)`);
}

await main();
