package redact

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

const generatedHeader = "Code generated by tests/gen-redact-rules.ts from spec/redact.cue. DO NOT EDIT."

func readRepoFile(t *testing.T, path ...string) string {
	t.Helper()
	parts := append([]string{"..", ".."}, path...)
	data, err := os.ReadFile(filepath.Join(parts...))
	if err != nil {
		t.Fatalf("read %s: %v", filepath.Join(path...), err)
	}
	return string(data)
}

// TestGeneratedFilesCarryTheHeader makes an accidental hand edit obvious: both
// generated artifacts announce where they come from.
func TestGeneratedFilesCarryTheHeader(t *testing.T) {
	for _, path := range [][]string{
		{"internal", "redact", "rules_gen.go"},
		{"src", "redact-patterns.ts"},
	} {
		firstLine := strings.SplitN(readRepoFile(t, path...), "\n", 2)[0]
		if firstLine != "// "+generatedHeader {
			t.Errorf("%s: first line = %q, want the generated header", filepath.Join(path...), firstLine)
		}
	}
}

// TestSourceDigestIsShared proves the three artifacts came from one document:
// the Go constant, the TypeScript constant and the CI comment agree.
func TestSourceDigestIsShared(t *testing.T) {
	goText := readRepoFile(t, "internal", "redact", "rules_gen.go")
	if !strings.Contains(goText, `const SourceDigest = "`+SourceDigest+`"`) {
		t.Errorf("rules_gen.go does not carry SourceDigest %q", SourceDigest)
	}

	tsMatch := regexp.MustCompile(`REDACT_SOURCE_DIGEST\s*=\s*"([0-9a-f]{64})"`).
		FindStringSubmatch(readRepoFile(t, "src", "redact-patterns.ts"))
	if tsMatch == nil || tsMatch[1] != SourceDigest {
		t.Errorf("src/redact-patterns.ts digest = %v, want %q", tsMatch, SourceDigest)
	}

	workflowMatch := regexp.MustCompile(`# redact-source-digest: ([0-9a-f]{64})`).
		FindStringSubmatch(readRepoFile(t, ".github", "workflows", "privacy-guard.yml"))
	if workflowMatch == nil || workflowMatch[1] != SourceDigest {
		t.Errorf("privacy-guard.yml digest = %v, want %q", workflowMatch, SourceDigest)
	}
}

// TestWorkflowPatternMatchesGuards proves the CI pattern is exactly the guard
// alternatives of the generated rules plus the path guards: no hand-written
// alternative can survive a regeneration.
func TestWorkflowPatternMatchesGuards(t *testing.T) {
	workflow := readRepoFile(t, ".github", "workflows", "privacy-guard.yml")
	match := regexp.MustCompile(`PATTERN='([^']+)'`).FindStringSubmatch(workflow)
	if match == nil {
		t.Fatal("privacy-guard.yml has no PATTERN line")
	}
	alternatives := make([]string, 0, len(rules)+len(pathGuards))
	for _, rule := range rules {
		if rule.Guard != "" {
			alternatives = append(alternatives, rule.Guard)
		}
	}
	alternatives = append(alternatives, pathGuards...)
	want := strings.Join(alternatives, "|")
	if match[1] != want {
		t.Errorf("PATTERN differs from the generated guards (got %s, want %s)", match[1], want)
	}
}

// TestRuleNamesLiveInTheRulesDocument keeps the generated rule list tied to
// spec/redact.cue: a rule only exists if the source document names it.
func TestRuleNamesLiveInTheRulesDocument(t *testing.T) {
	document := readRepoFile(t, "spec", "redact.cue")
	names := make([]string, 0, len(rules)+len(homePrefixRules))
	for _, rule := range rules {
		names = append(names, rule.Name)
	}
	for _, rule := range homePrefixRules {
		names = append(names, rule.Name)
	}
	for _, name := range names {
		pattern := regexp.MustCompile(`name:\s+"` + regexp.QuoteMeta(name) + `"`)
		if !pattern.MatchString(document) {
			t.Errorf("rule %q is not named in spec/redact.cue", name)
		}
	}
}
